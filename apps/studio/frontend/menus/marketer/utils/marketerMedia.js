function path(id, ext) {
  const cut = id.indexOf('-')
  return `/marketer-media/${id.slice(0, cut)}/${id.slice(cut + 1)}.${ext}`
}

/** @returns {string | null} */
export const mkImage = id => (IMAGES.has(id) ? path(id, 'webp') : null)
/** @returns {string | null} */
export const mkVideo = id => (VIDEOS.has(id) ? path(id, 'mp4') : null)
/** @returns {string | null} */
export const mkPoster = id => (VIDEOS.has(id) ? path(id, 'poster.webp') : mkImage(id))
/** id ทั้งหมดในกลุ่ม เช่น mkGroup('showcase') */
export const mkGroup = group => [...IMAGES].filter(id => id.startsWith(`${group}-`))
